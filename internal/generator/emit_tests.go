// EmitTests returns the Go source for internal/definitions/<country>_test.go.
func EmitTests(rf *RegionFile) ([]byte, error) {
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by gen-holidays from definitions/%s.yaml@%s. DO NOT EDIT.\n\n", rf.Country, SourceTag)
	fmt.Fprintln(&buf, "package definitions_test")
	fmt.Fprintln(&buf)
	fmt.Fprintln(&buf, "import (")
	fmt.Fprintln(&buf, "\t\"fmt\"")
	fmt.Fprintln(&buf)
	fmt.Fprintln(&buf, "\tholidays \"github.com/holidays/go-holidays\"")
	fmt.Fprintln(&buf)
	fmt.Fprintln(&buf, "\t. \"github.com/onsi/ginkgo/v2\"")
	fmt.Fprintln(&buf, "\t. \"github.com/onsi/gomega\"")
	fmt.Fprintln(&buf, ")")
	fmt.Fprintln(&buf)

	fmt.Fprintf(&buf, "var _ = Describe(%s, func() {\n", strconv.Quote(rf.Country))
	for i, ts := range rf.Tests {
		writeDescribeTable(&buf, rf.Country, i, ts)
	}
	fmt.Fprintln(&buf, "})")

	src, err := format.Source(buf.Bytes())
	if err != nil {
		return buf.Bytes(), fmt.Errorf("gofmt %s_test: %w (raw output kept for debugging)", rf.Country, err)
	}
	return src, nil
}

// EmitTestHelpers returns the Go source for internal/definitions/helpers_test.go.
// This file is regenerated on every run and is the single source of shared
// helpers and the Ginkgo bootstrap. Region init() functions are triggered by
// the root holidays package, which blank-imports internal/definitions.
func EmitTestHelpers() []byte {
	return []byte(`// Code generated by gen-holidays. DO NOT EDIT.

package definitions_test

import (
	"testing"
	"time"

	holidays "github.com/holidays/go-holidays"

	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"
)

func TestDefinitions(t *testing.T) {
	RegisterFailHandler(Fail)
	RunSpecs(t, "definitions suite")
}

func parseFlex(s string) (time.Time, error) {
	return time.Parse("2006-1-2", s)
}

func hasNamed(hs []holidays.Holiday, name string) bool {
	for _, h := range hs {
		if h.Name == name {
			return true
		}
	}
	return false
}
`)
}

// writeDescribeTable emits one Ginkgo DescribeTable for a TestSpec, with one
// Entry per date. The three expectation cases (named holiday, no holiday,
// any holiday) mirror the semantics of the previous func-based tests.
func writeDescribeTable(buf *bytes.Buffer, country string, idx int, ts TestSpec) {
	var (
		hint      = testHint(ts)
		tableName = fmt.Sprintf("%03d_%s", idx, hint)
	)
	fmt.Fprintf(buf, "\tDescribeTable(%s, func(s string) {\n", strconv.Quote(tableName))
	fmt.Fprintf(buf, "\t\topts := holidays.Options{Regions: %s", stringSliceLit(ts.Regions))
	for _, o := range ts.Options {
		switch o {
		case "informal":
			fmt.Fprint(buf, ", Informal: true")
		case "observed":
			fmt.Fprint(buf, ", Observed: true")
		}
	}
	fmt.Fprintln(buf, "}")
	buf.WriteString("\t\td, err := parseFlex(s)\n")
	buf.WriteString("\t\tExpect(err).NotTo(HaveOccurred())\n")
	buf.WriteString("\t\thols, err := holidays.On(d, opts)\n")
	buf.WriteString("\t\tExpect(err).NotTo(HaveOccurred())\n")

	switch {
	case ts.Expected.Name != "":
		fmt.Fprintf(buf, "\t\tExpect(hasNamed(hols, %s)).To(BeTrue(), fmt.Sprintf(\"On(%%s, %%v): want holiday %%q, got %%v\", s, opts.Regions, %s, hols))\n", strconv.Quote(ts.Expected.Name), strconv.Quote(ts.Expected.Name))
	case ts.Expected.Holiday != nil && !*ts.Expected.Holiday:
		buf.WriteString("\t\tExpect(hols).To(BeEmpty(), fmt.Sprintf(\"On(%s, %v): expected no holiday, got %v\", s, opts.Regions, hols))\n")
	case ts.Expected.Holiday != nil && *ts.Expected.Holiday:
		buf.WriteString("\t\tExpect(hols).ToNot(BeEmpty(), fmt.Sprintf(\"On(%s, %v): expected a holiday, got none\", s, opts.Regions))\n")
	}
	buf.WriteString("\t},\n")
	for _, d := range ts.Dates {
		fmt.Fprintf(buf, "\t\tEntry(%s, %s),\n", strconv.Quote(d), strconv.Quote(d))
	}
	buf.WriteString("\t)\n\n")
}

func testHint(ts TestSpec) string {
	if ts.Expected.Name != "" {
		return sanitizeIdent(ts.Expected.Name)
	}
	if ts.Expected.Holiday != nil && !*ts.Expected.Holiday {
		return "Negative"
	}
	return "Positive"
}

// sanitizeIdent makes a Go-safe identifier fragment from arbitrary text.
func sanitizeIdent(s string) string {
	var (
		b     strings.Builder
		upper = true
	)
	for _, r := range s {
		switch {
		case unicode.IsLetter(r) || unicode.IsDigit(r):
			if upper {
				b.WriteRune(unicode.ToUpper(r))
				upper = false
			} else {
				b.WriteRune(r)
			}
		default:
			upper = true
		}
	}
	if b.Len() == 0 {
		return "Unnamed"
	}
	return b.String()
}
